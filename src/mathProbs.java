public class mathProbs {
    public static void main(String[] args){

//        declaring PI
        double piNum = Math.PI;
        System.out.println(piNum);

//        declaring exponential constant
        double exponentialCons = Math.E;
        System.out.println(exponentialCons);

//        declaring power of a number
        double powerOfNum;
        powerOfNum = Math.pow(2, 3); // 2^3
        System.out.println(powerOfNum);



//      finding the absolute value
        double absNum;
        absNum = Math.abs(-28);
        System.out.println(absNum);


//        find the square root
        double squRt;
        squRt = Math.sqrt(9);
        System.out.println(squRt);

//        round the value
        double roundNum;
        roundNum = Math.round(3.14);
        System.out.println(roundNum);

//        ceiling the number
        double ceilNum;
        ceilNum = Math.ceil(3.14);
        System.out.println(ceilNum);

//        floor the number
        double floorNum;
        floorNum = Math.floor(3.14);
        System.out.println(floorNum);

//        max number
        double maxNum;
        maxNum = Math.max(20, 45);
        System.out.println(maxNum);

//        min number
        double minNum;
        minNum = Math.min(30, 76);
        System.out.println(minNum);




    }
}
